/** Plural bucket: German, Albanian and English all use 1 / many. */
export function pluralKey(_lang: Lang, n: number): '1' | '2' | '5' {
  return n === 1 ? '1' : '5';
}

/** First letter upper-case (Intl weekday/month names are lower-case in DE/SQ). */
export const capitalize = (s: string) => (s ? s[0].toLocaleUpperCase() + s.slice(1) : s);

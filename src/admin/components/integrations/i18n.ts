export type ITKey = keyof (typeof IT)['de'];
export const useIT = () => useDict(IT, 'admin');

/** A log/event text in all three languages (log entries are stored, then shown in the admin language). */
export function l10nOf(key: ITKey, vars?: Record<string, string | number>, perLang?: Partial<Record<keyof L10n, Record<string, string | number>>>): L10n {
  return {
    de: interpolate(IT.de[key], { ...vars, ...perLang?.de }),
    sq: interpolate(IT.sq[key], { ...vars, ...perLang?.sq }),
    en: interpolate(IT.en[key], { ...vars, ...perLang?.en }),
  };
}
